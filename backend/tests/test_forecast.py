import numpy as np
import pandas as pd
import pytest

from app import forecast as fc


def simulate_garch(n, omega=0.02, alpha=0.08, beta=0.9, seed=0):
    """Daily returns in percent from a known GARCH(1,1)."""
    rng = np.random.default_rng(seed)
    r = np.empty(n)
    s2 = omega / (1 - alpha - beta)
    for t in range(n):
        r[t] = np.sqrt(s2) * rng.standard_normal()
        s2 = omega + alpha * r[t] ** 2 + beta * s2
    return r


def prices_from_pct(r, start="2015-01-01"):
    idx = pd.bdate_range(start, periods=len(r) + 1)
    return pd.Series(100 * np.exp(np.concatenate([[0], np.cumsum(r / 100)])), index=idx)


def test_garch_fit_recovers_known_parameters():
    r = simulate_garch(6000, seed=1)
    g = fc.garch_fit(r - r.mean())
    assert g.alpha == pytest.approx(0.08, abs=0.03)
    assert g.beta == pytest.approx(0.90, abs=0.04)
    assert g.persistence < 1


def test_garch_filter_matches_loop():
    r = np.random.default_rng(2).normal(0, 1, 50)
    g = fc.Garch(0.05, 0.1, 0.85)
    s2 = fc.garch_filter(r, g, 1.0)
    loop = [1.0]
    for x in r:
        loop.append(g.omega + g.alpha * x**2 + g.beta * loop[-1])
    assert np.allclose(s2, loop)


def test_long_horizon_forecast_tends_to_long_run_variance():
    g = fc.Garch(0.02, 0.08, 0.9)
    assert fc.garch_horizon_var(g, 5.0, 5000) == pytest.approx(g.long_run_var, rel=0.05)
    assert fc.garch_horizon_var(g, 5.0, 1) == pytest.approx(5.0)


def test_realised_vol_ahead_looks_only_forward():
    r = pd.Series([0.0] * 5 + [0.01] * 5)
    ahead = fc.realised_vol_ahead(r, h=5)
    assert ahead.iloc[4] == pytest.approx(0.01 * np.sqrt(252))  # days 5..9
    assert ahead.iloc[0] == pytest.approx(np.sqrt(0.0001 * 1 / 5 * 252))  # days 1..5, one non-zero
    assert ahead.iloc[-5:].isna().all()


@pytest.fixture(scope="module")
def walk():
    close = prices_from_pct(simulate_garch(3000, seed=3))
    return close, fc.walk_forward(close, h=21, min_train=500, refit_every=126)


def test_walk_forward_has_every_model_and_no_gaps(walk):
    _, out = walk
    assert set(fc.MODELS) <= set(out.columns)
    assert len(out) > 2000 and out.notna().all().all()
    assert (out[fc.MODELS] > 0).all().all()


def test_walk_forward_has_no_look_ahead(walk):
    close, out = walk
    day = out.index[100]
    changed = close.copy()
    changed[changed.index > day] *= np.linspace(1, 3, (changed.index > day).sum())  # rewrite the future
    out2 = fc.walk_forward(changed, h=21, min_train=500, refit_every=126)
    for m in fc.MODELS:
        assert out2.loc[day, m] == pytest.approx(out.loc[day, m]), m
    assert out2.loc[day, "target"] != pytest.approx(out.loc[day, "target"])  # only the target can change


def test_garch_beats_naive_baselines_on_garch_data(walk):
    # With enough data generated by a real GARCH process, the GARCH forecast should win.
    _, out = walk
    table = fc.evaluate(out)
    assert table.loc["garch", "qlike"] < table.loc["long_run", "qlike"]
    assert table.loc["garch", "qlike"] < table.loc["last_month", "qlike"]
    assert table.loc["last_month", "rmse_vs_baseline"] == pytest.approx(0)


def test_evaluate_perfect_forecast_scores_zero():
    idx = pd.RangeIndex(10)
    y = pd.Series(np.linspace(0.1, 0.3, 10), index=idx)
    df = pd.DataFrame({"target": y, **{m: y for m in fc.MODELS}})
    table = fc.evaluate(df)
    assert (table[["rmse", "mae", "qlike"]].abs() < 1e-12).all().all()


def test_latest_forecast_is_sensible():
    close = prices_from_pct(simulate_garch(1500, seed=4))
    f = fc.latest_forecast(close)
    assert 0.05 < f["garch_next_month"] < 1.5
    assert 0.5 < f["persistence"] < 1 and f["half_life_days"] > 0
